---------Politicas y restricciones--------


USE Gimnasio_Reserva;
GO

-- RECEPCION NO PUEDE ELIMINAR SOCIOS

DENY DELETE
ON dbo.Socio TO rol_recepcion;
GO

-- RECEPCION NO PUEDE ELIMINAR RESERVAS

DENY DELETE
ON dbo.Reserva TO rol_recepcion;
GO

-- RECEPCION NO PUEDE ELIMINAR PAGOS

DENY DELETE
ON dbo.Pago TO rol_recepcion;
GO

-- ENTRENADORES NO PUEDEN MODIFICAR CLASES

DENY INSERT, UPDATE, DELETE
ON dbo.Clases TO rol_entrenador;
GO

-- ENTRENADORES NO PUEDEN MODIFICAR PROGRAMACIONES

DENY INSERT, UPDATE, DELETE
ON dbo.Programacion_clase TO rol_entrenador;
GO

-- ENTRENADORES NO PUEDEN CONSULTAR PAGOS

DENY SELECT, INSERT, UPDATE, DELETE
ON dbo.Pago TO rol_entrenador;
GO

-- ENTRENADORES NO PUEDEN CONSULTAR DATOS DE SOCIOS

DENY SELECT, INSERT, UPDATE, DELETE
ON dbo.Socio TO rol_entrenador;
GO

-- SOCIOS NO PUEDEN CONSULTAR PAGOS

DENY SELECT, INSERT, UPDATE, DELETE
ON dbo.Pago TO rol_socio;
GO

-- SOCIOS NO PUEDEN CONSULTAR DATOS DE OTROS SOCIOS

DENY SELECT, INSERT, UPDATE, DELETE
ON dbo.Socio TO rol_socio;
GO

-- SOCIOS NO PUEDEN MODIFICAR RESERVAS

DENY INSERT, UPDATE, DELETE
ON dbo.Reserva TO rol_socio;
GO
